-- =====================================================================
-- Vários clientes (prefeituras, câmaras...) no mesmo banco
--
-- Como usar: cole este arquivo inteiro no SQL Editor do Supabase e clique
-- em "Run". Rode DEPOIS de todos os outros scripts. Pode ser executado
-- mais de uma vez sem problema.
--
-- O que ele faz:
--   • Cria a tabela "clientes". Tudo o que já existe no banco passa a ser
--     do cliente nº 1 (dê a ele o nome certo no painel, aba Clientes).
--   • Cada usuário pertence a UM cliente (usuarios.cliente_id) e só enxerga
--     os bens, o levantamento, a reavaliação, os documentos, o histórico,
--     as sobras, as fotos e os usuários desse cliente.
--   • Usuário "da empresa" (usuarios.geral = true): administrador que pode
--     trocar de cliente no painel e cadastrar clientes novos. Os
--     administradores que já existem viram "da empresa".
--   • Cliente desativado: os usuários dele deixam de entrar nos dados.
--   • Fotos e laudos do cliente 1 continuam onde estão; os dos clientes
--     novos ficam na pasta c<nº>/ do bucket "fotos".
--   • Bancos de preços (catálogo, PNCP, LicitaCon) continuam comuns a todos.
-- =====================================================================

-- ---------- clientes ----------
create table if not exists public.clientes (
  id        integer generated by default as identity primary key,
  nome      text not null,
  cnpj      text,
  municipio text,
  sistema   text,                 -- sistema de origem (Governança Brasil, IPM, Betha...)
  pasta     text unique,          -- prefixo das fotos no bucket ('' = cliente 1, antigo)
  ativo     boolean not null default true,
  criado_em timestamptz not null default now()
);
alter table public.clientes enable row level security;

create or replace function public.clientes_pasta()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then new.pasta := coalesce(new.pasta, 'c' || new.id || '/');
  else new.pasta := old.pasta;  -- a pasta nunca muda
  end if;
  new.nome := trim(new.nome);
  if new.nome = '' then raise exception 'Informe o nome do cliente.'; end if;
  return new;
end $$;
drop trigger if exists clientes_pasta on public.clientes;
create trigger clientes_pasta before insert or update on public.clientes
  for each row execute function public.clientes_pasta();

insert into public.clientes (id, nome, pasta) values (1, 'Cliente 1 (dê o nome no painel)', '')
on conflict (id) do nothing;
do $$ begin
  perform setval(pg_get_serial_sequence('public.clientes', 'id'), greatest((select max(id) from public.clientes), 1));
end $$;

-- ---------- usuário: a qual cliente pertence ----------
alter table public.usuarios add column if not exists cliente_id integer references public.clientes(id);
alter table public.usuarios add column if not exists geral boolean not null default false;
update public.usuarios set cliente_id = 1 where cliente_id is null;
alter table public.usuarios alter column cliente_id set not null;
-- quem já era administrador vira "da empresa" (só na primeira vez que o script roda)
do $$ begin
  if not exists (select 1 from public.usuarios where geral) then
    update public.usuarios u set geral = true where exists (select 1 from public.admins a where a.user_id = u.user_id);
  end if;
end $$;
create index if not exists usuarios_cliente on public.usuarios (cliente_id);

-- cliente de quem está logado (null = sem acesso: usuário inativo ou cliente desativado)
create or replace function public.cliente_atual()
returns integer language sql stable security definer set search_path = public as $$
  select u.cliente_id from public.usuarios u join public.clientes c on c.id = u.cliente_id
   where u.user_id = auth.uid() and u.ativo and (c.ativo or u.geral);
$$;

-- administrador "da empresa": vê a lista de clientes e troca de cliente
create or replace function public.eh_geral()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.usuarios u where u.user_id = auth.uid() and u.ativo and u.geral)
     and exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;

-- dono de um arquivo do bucket pelo caminho: c<nº>/... = cliente nº; outros caminhos = cliente 1
create or replace function public.cliente_do_arquivo(p_nome text)
returns integer language sql immutable as $$
  select case when p_nome ~ '^c[0-9]+/' then substring(p_nome from '^c([0-9]+)/')::integer else 1 end;
$$;

-- dados do cliente atual, para o app e o painel
create or replace function public.meu_cliente()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id', c.id, 'nome', c.nome, 'pasta', coalesce(c.pasta, ''),
                            'ativo', c.ativo, 'geral', public.eh_geral())
    from public.clientes c where c.id = public.cliente_atual();
$$;

-- troca o cliente em que o usuário "da empresa" está trabalhando
create or replace function public.escolher_cliente(p_id integer)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if not public.eh_geral() then
    raise exception 'Só a equipe da empresa pode trocar de cliente.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.clientes where id = p_id) then
    raise exception 'Cliente não encontrado.';
  end if;
  update public.usuarios set cliente_id = p_id, atualizado_em = now() where user_id = auth.uid();
  return public.meu_cliente();
end $$;

revoke all on function public.escolher_cliente(integer) from public, anon;
grant execute on function public.cliente_atual(), public.eh_geral(), public.meu_cliente(),
  public.escolher_cliente(integer), public.cliente_do_arquivo(text) to authenticated;

drop policy if exists cli_ler on public.clientes;
create policy cli_ler on public.clientes for select to authenticated
  using (id = (select public.cliente_atual()) or (select public.eh_geral()));
drop policy if exists cli_incluir on public.clientes;
create policy cli_incluir on public.clientes for insert to authenticated with check ((select public.eh_geral()));
drop policy if exists cli_alterar on public.clientes;
create policy cli_alterar on public.clientes for update to authenticated
  using ((select public.eh_geral())) with check ((select public.eh_geral()));
revoke all on public.clientes from anon;
grant select, insert, update on public.clientes to authenticated;

-- ---------- coluna cliente_id em todas as tabelas de dados ----------
do $$
declare t text;
begin
  foreach t in array array['bens','levantamento','localizacoes','motivos','comissoes','configuracao',
                           'reavaliacao','referencias','localizacoes_concluidas','historico','sobras'] loop
    execute format('alter table public.%I add column if not exists cliente_id integer', t);
    execute format('update public.%I set cliente_id = 1 where cliente_id is null', t);
    execute format('alter table public.%I alter column cliente_id set not null', t);
    execute format('alter table public.%I alter column cliente_id set default public.cliente_atual()', t);
    if not exists (select 1 from pg_constraint where conrelid = ('public.' || t)::regclass and conname = t || '_cliente_fk') then
      execute format('alter table public.%I add constraint %I foreign key (cliente_id) references public.clientes(id)', t, t || '_cliente_fk');
    end if;
  end loop;
end $$;

-- ---------- chaves: o mesmo código pode existir em clientes diferentes ----------
-- solta o vínculo levantamento -> bens e as chaves antigas (só se ainda forem as antigas)
do $$
declare r record;
begin
  for r in select conrelid::regclass as tab, conname from pg_constraint
            where conrelid = 'public.levantamento'::regclass and contype = 'f'
              and confrelid = 'public.bens'::regclass
              and array_length(conkey, 1) = 1 loop
    execute format('alter table %s drop constraint %I', r.tab, r.conname);
  end loop;
  for r in select conrelid::regclass as tab, conname from pg_constraint
            where conrelid = 'public.levantamento'::regclass and contype = 'u'
              and array_length(conkey, 1) = 1 loop
    execute format('alter table %s drop constraint %I', r.tab, r.conname);
  end loop;
end $$;

do $$
declare r record; par text[];
begin
  foreach par slice 1 in array array[['bens','codigo'],['localizacoes','cod'],['motivos','cod'],['comissoes','cod'],
      ['configuracao','id'],['reavaliacao','codigo'],['referencias','chave'],['localizacoes_concluidas','cod']] loop
    select conname, array_length(conkey, 1) as n into r from pg_constraint
     where conrelid = ('public.' || par[1])::regclass and contype = 'p';
    if r.n = 1 then
      execute format('alter table public.%I drop constraint %I', par[1], r.conname);
      execute format('alter table public.%I add primary key (cliente_id, %I)', par[1], par[2]);
    end if;
  end loop;
end $$;

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'levantamento_cliente_codigo_key') then
    alter table public.levantamento add constraint levantamento_cliente_codigo_key unique (cliente_id, codigo);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'levantamento_bem_fk') then
    alter table public.levantamento add constraint levantamento_bem_fk
      foreign key (cliente_id, codigo) references public.bens (cliente_id, codigo);
  end if;
end $$;
create index if not exists historico_cliente on public.historico (cliente_id, tabela, codigo);
create index if not exists sobras_cliente on public.sobras (cliente_id);

-- ---------- histórico: grava o cliente da própria linha ----------
create or replace function public.registrar_historico()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  ign text[] := array['id','atualizado_em','atualizado_por','atualizado_por_nome','usuario','usuario_nome'];
  j_old jsonb; j_new jsonb; chg text[]; lin jsonb;
begin
  if tg_op <> 'INSERT' then j_old := to_jsonb(old) - ign; end if;
  if tg_op <> 'DELETE' then j_new := to_jsonb(new) - ign; end if;
  lin := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  if tg_op = 'UPDATE' then
    select array_agg(n.key order by n.key) into chg
      from jsonb_each(j_new) n where n.value is distinct from (j_old -> n.key);
    if chg is null then return null; end if;   -- nada mudou de verdade
    j_old := (select jsonb_object_agg(k, j_old -> k) from unnest(chg) k);
    j_new := (select jsonb_object_agg(k, j_new -> k) from unnest(chg) k);
  end if;
  insert into public.historico (cliente_id, tabela, codigo, acao, campos, antes, depois, usuario, usuario_nome)
  values ((lin ->> 'cliente_id')::integer, tg_table_name,
          coalesce(lin ->> 'codigo', lin ->> 'cod', lin ->> 'chave', lin ->> 'id'),
          case tg_op when 'INSERT' then 'incluiu' when 'UPDATE' then 'alterou' else 'excluiu' end,
          chg, jsonb_strip_nulls(j_old - 'cliente_id'), jsonb_strip_nulls(j_new - 'cliente_id'),
          auth.uid(), case when auth.uid() is null then 'servidor' else public.nome_do_usuario() end);
  return null;
end $$;

-- ---------- regras de acesso (RLS): só o próprio cliente ----------
-- apaga as regras antigas destas tabelas e cria as novas
do $$
declare r record;
begin
  for r in select tablename, policyname from pg_policies where schemaname = 'public'
            and tablename in ('bens','levantamento','localizacoes','motivos','comissoes','configuracao',
                              'reavaliacao','referencias','localizacoes_concluidas','historico','sobras','usuarios') loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
  for r in select policyname from pg_policies where schemaname = 'storage' and tablename = 'objects'
            and policyname in ('fotos_ler','fotos_enviar','fotos_excluir') loop
    execute format('drop policy %I on storage.objects', r.policyname);
  end loop;
end $$;

-- bens: todos do cliente leem e atualizam (a trigger proteger_bens deixa a equipe de campo mudar só a placa)
create policy bens_ler on public.bens for select to authenticated
  using (cliente_id = (select public.cliente_atual()));
create policy bens_atualizar on public.bens for update to authenticated
  using (cliente_id = (select public.cliente_atual())) with check (cliente_id = (select public.cliente_atual()));
create policy bens_incluir on public.bens for insert to authenticated
  with check (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));
create policy bens_excluir on public.bens for delete to authenticated
  using (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));

-- levantamento: equipe do cliente lê, inclui e altera; só administrador exclui
create policy lev_ler on public.levantamento for select to authenticated
  using (cliente_id = (select public.cliente_atual()));
create policy lev_incluir on public.levantamento for insert to authenticated
  with check (cliente_id = (select public.cliente_atual()));
create policy lev_atualizar on public.levantamento for update to authenticated
  using (cliente_id = (select public.cliente_atual())) with check (cliente_id = (select public.cliente_atual()));
create policy lev_excluir on public.levantamento for delete to authenticated
  using (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));

-- tabelas que a equipe só lê e o administrador do cliente mantém
do $$
declare t text;
begin
  foreach t in array array['localizacoes','motivos','comissoes','configuracao','reavaliacao','referencias'] loop
    execute format('create policy %I on public.%I for select to authenticated using (cliente_id = (select public.cliente_atual()))', t || '_ler', t);
    execute format('create policy %I on public.%I for all to authenticated using (cliente_id = (select public.cliente_atual()) and (select public.is_admin())) with check (cliente_id = (select public.cliente_atual()) and (select public.is_admin()))', t || '_admin', t);
  end loop;
end $$;

-- conclusão das localizações: equipe conclui, administrador reabre
create policy lc_ler on public.localizacoes_concluidas for select to authenticated
  using (cliente_id = (select public.cliente_atual()));
create policy lc_concluir on public.localizacoes_concluidas for insert to authenticated
  with check (cliente_id = (select public.cliente_atual()));
create policy lc_reabrir on public.localizacoes_concluidas for delete to authenticated
  using (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));

-- histórico: só administrador do cliente lê
create policy hist_ler on public.historico for select to authenticated
  using (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));

-- sobras (bens sem cadastro)
create policy sob_ler on public.sobras for select to authenticated
  using (cliente_id = (select public.cliente_atual()));
create policy sob_incluir on public.sobras for insert to authenticated
  with check (cliente_id = (select public.cliente_atual()));
create policy sob_alterar on public.sobras for update to authenticated
  using (cliente_id = (select public.cliente_atual())
         and ((select public.is_admin()) or (usuario = auth.uid() and situacao = 'pendente')))
  with check (cliente_id = (select public.cliente_atual())
         and ((select public.is_admin()) or (usuario = auth.uid() and situacao = 'pendente')));
create policy sob_excluir on public.sobras for delete to authenticated
  using (cliente_id = (select public.cliente_atual()) and (select public.is_admin()));

-- usuários: cada um lê o próprio cadastro; o administrador lê os do seu cliente
create policy usu_ler on public.usuarios for select to authenticated
  using (user_id = auth.uid()
         or ((select public.is_admin()) and cliente_id = (select public.cliente_atual())));

-- fotos, fotos das sobras e laudos: só do próprio cliente (pela pasta)
create policy fotos_ler on storage.objects for select to authenticated
  using (bucket_id = 'fotos' and public.cliente_do_arquivo(name) = (select public.cliente_atual()));
create policy fotos_enviar on storage.objects for insert to authenticated
  with check (bucket_id = 'fotos' and public.cliente_do_arquivo(name) = (select public.cliente_atual()));
create policy fotos_excluir on storage.objects for delete to authenticated
  using (bucket_id = 'fotos' and public.cliente_do_arquivo(name) = (select public.cliente_atual())
         and (select public.is_admin()));

-- conferência: clientes e quantos bens cada um tem
select c.id, c.nome, c.ativo, coalesce(c.pasta, '') as pasta,
       (select count(*) from public.bens b where b.cliente_id = c.id) as bens,
       (select count(*) from public.usuarios u where u.cliente_id = c.id) as usuarios
  from public.clientes c order by c.id;
