-- =====================================================================
-- Avisos e notificações no celular (app de campo)
--
-- Como usar: cole este arquivo inteiro no SQL Editor do Supabase e clique
-- em "Run". Rode DEPOIS do clientes.sql e do acesso-teste.sql. Pode ser
-- executado mais de uma vez sem problema.
--
-- O que ele faz:
--   • avisos: cada mensagem do administrador ou do sistema, por cliente.
--     Vazio em "para" = todos do cliente. Quem recebe vê no app (sino do menu)
--     e, se ligou as notificações, também na tela do celular.
--   • avisos_lidos: quem já abriu cada aviso (o painel mostra quantos leram).
--   • avisos_pref: cada pessoa escolhe se quer notificação dos avisos do
--     administrador e dos avisos automáticos. Sem escolha = recebe tudo.
--   • push_inscricoes: os aparelhos que aceitaram notificações. Cada um só
--     vê e apaga os seus; quem envia é a função "avisos" no servidor.
--   • push_config: chaves das notificações e o segredo do agendador. Só o
--     servidor lê (ninguém do navegador enxerga esta tabela).
--   • Aviso automático "Localização reaberta" para quem tinha concluído.
--   • Agendador (pg_cron) que chama a função de hora em hora: avisa 3 dias
--     e 1 dia antes de o acesso de teste vencer e envia o que ficou pendente.
-- =====================================================================

create extension if not exists pgcrypto with schema extensions;

-- ---------- chaves das notificações (só o servidor lê) ----------
create table if not exists public.push_config (
  id             int primary key default 1 check (id = 1),
  vapid_publica  text,
  vapid_privada  jsonb,
  segredo_rotina text not null default encode(extensions.gen_random_bytes(24), 'hex')
);
insert into public.push_config (id) values (1) on conflict (id) do nothing;
alter table public.push_config enable row level security;
revoke all on public.push_config from anon, authenticated;

-- ---------- aparelhos inscritos ----------
create table if not exists public.push_inscricoes (
  endpoint   text primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  cliente_id integer,
  p256dh     text not null,
  auth       text not null,
  aparelho   text,
  criado_em  timestamptz not null default now(),
  ultimo_ok  timestamptz,
  falhas     integer not null default 0
);
create index if not exists push_inscricoes_user on public.push_inscricoes (user_id);
alter table public.push_inscricoes enable row level security;
drop policy if exists push_ler on public.push_inscricoes;
create policy push_ler on public.push_inscricoes for select to authenticated using (user_id = auth.uid());
revoke all on public.push_inscricoes from anon;
grant select on public.push_inscricoes to authenticated;

-- grava o aparelho de quem está logado (se o celular era de outra pessoa, passa a ser deste usuário)
create or replace function public.registrar_aparelho(p_endpoint text, p_p256dh text, p_auth text, p_aparelho text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or not public.usuario_ativo() then
    raise exception 'Usuário sem acesso.' using errcode = '42501';
  end if;
  if coalesce(p_endpoint, '') !~ '^https://' or length(p_endpoint) > 1000
     or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then
    raise exception 'Inscrição inválida.';
  end if;
  insert into public.push_inscricoes (endpoint, user_id, cliente_id, p256dh, auth, aparelho)
  values (p_endpoint, auth.uid(), public.cliente_atual(), p_p256dh, p_auth, left(p_aparelho, 80))
  on conflict (endpoint) do update
    set user_id = excluded.user_id, cliente_id = excluded.cliente_id, p256dh = excluded.p256dh,
        auth = excluded.auth, aparelho = excluded.aparelho, falhas = 0;
end $$;

create or replace function public.remover_aparelho(p_endpoint text)
returns void language sql security definer set search_path = public as $$
  delete from public.push_inscricoes where endpoint = p_endpoint and user_id = auth.uid();
$$;

-- usada só pela função "avisos" (servidor): conta falhas de entrega
create or replace function public.push_falhou(p_endpoint text)
returns void language sql security definer set search_path = public as $$
  update public.push_inscricoes set falhas = falhas + 1 where endpoint = p_endpoint;
$$;

revoke all on function public.registrar_aparelho(text, text, text, text), public.remover_aparelho(text),
  public.push_falhou(text) from public, anon, authenticated;
grant execute on function public.registrar_aparelho(text, text, text, text), public.remover_aparelho(text) to authenticated;
grant execute on function public.push_falhou(text) to service_role;

-- ---------- avisos ----------
create table if not exists public.avisos (
  id              bigint generated by default as identity primary key,
  cliente_id      integer not null references public.clientes(id),
  para            uuid references auth.users(id) on delete cascade,  -- vazio = todos do cliente
  tipo            text not null default 'admin' check (tipo in ('admin', 'sistema')),
  categoria       text,                -- mensagem | prazo | localizacao
  chave           text unique,         -- evita aviso automático repetido
  titulo          text not null,
  texto           text not null,
  url             text,
  criado_por      uuid,
  criado_nome     text,
  criado_em       timestamptz not null default now(),
  enviado_em      timestamptz,         -- quando a função tentou mandar aos aparelhos
  pessoas         integer,             -- quantas pessoas deviam receber
  sem_notificacao integer,             -- quantas desligaram este tipo de aviso
  entregues       integer              -- quantos aparelhos receberam a notificação
);
create index if not exists avisos_cliente on public.avisos (cliente_id, criado_em desc);
create index if not exists avisos_para on public.avisos (para) where para is not null;
create index if not exists avisos_pendentes on public.avisos (criado_em) where enviado_em is null;
alter table public.avisos enable row level security;
drop policy if exists avisos_ler on public.avisos;
create policy avisos_ler on public.avisos for select to authenticated using (
  (para = auth.uid() and (select public.usuario_ativo()))
  or (cliente_id = (select public.cliente_atual()) and (para is null or (select public.is_admin())))
);
revoke all on public.avisos from anon;
grant select on public.avisos to authenticated;   -- quem grava é a função "avisos" e as regras do banco

-- ---------- quem leu ----------
create table if not exists public.avisos_lidos (
  aviso_id bigint not null references public.avisos(id) on delete cascade,
  user_id  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  lido_em  timestamptz not null default now(),
  primary key (aviso_id, user_id)
);
alter table public.avisos_lidos enable row level security;
drop policy if exists lidos_ler on public.avisos_lidos;
drop policy if exists lidos_marcar on public.avisos_lidos;
create policy lidos_ler on public.avisos_lidos for select to authenticated using (
  user_id = auth.uid()
  or ((select public.is_admin()) and exists (select 1 from public.avisos a
        where a.id = aviso_id and a.cliente_id = (select public.cliente_atual())))
);
create policy lidos_marcar on public.avisos_lidos for insert to authenticated
  with check (user_id = auth.uid() and exists (select 1 from public.avisos a where a.id = aviso_id));
revoke all on public.avisos_lidos from anon;
grant select, insert on public.avisos_lidos to authenticated;

-- ---------- preferências de cada pessoa ----------
create table if not exists public.avisos_pref (
  user_id       uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  admin         boolean not null default true,   -- mensagens do administrador
  sistema       boolean not null default true,   -- avisos automáticos
  atualizado_em timestamptz not null default now()
);
alter table public.avisos_pref enable row level security;
drop policy if exists pref_ler on public.avisos_pref;
drop policy if exists pref_incluir on public.avisos_pref;
drop policy if exists pref_alterar on public.avisos_pref;
create policy pref_ler on public.avisos_pref for select to authenticated using (user_id = auth.uid());
create policy pref_incluir on public.avisos_pref for insert to authenticated with check (user_id = auth.uid());
create policy pref_alterar on public.avisos_pref for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
revoke all on public.avisos_pref from anon;
grant select, insert, update on public.avisos_pref to authenticated;

-- ---------- aviso automático: localização reaberta ----------
-- Quando o administrador reabre uma localização, quem tinha concluído recebe um aviso.
-- Dá para desligar no painel (Avisos > Avisos automáticos).
create or replace function public.avisar_localizacao_reaberta()
returns trigger language plpgsql security definer set search_path = public as $$
declare ligado boolean;
begin
  if old.concluido_por is null or old.concluido_por = auth.uid() then return null; end if;
  select coalesce((c.dados -> 'avisosAuto' ->> 'reaberta')::boolean, true) into ligado
    from public.configuracao c where c.cliente_id = old.cliente_id and c.id = 1;
  if ligado is false then return null; end if;
  insert into public.avisos (cliente_id, para, tipo, categoria, titulo, texto, criado_por, criado_nome)
  values (old.cliente_id, old.concluido_por, 'sistema', 'localizacao', 'Localização reaberta',
          'O administrador reabriu "' || coalesce(nullif(old.descricao, ''), old.cod) ||
          '", que você tinha concluído. Confira os bens dela de novo e conclua outra vez.',
          auth.uid(), coalesce(public.nome_do_usuario(), 'Administrador'));
  return null;
end $$;
drop trigger if exists avisar_localizacao_reaberta on public.localizacoes_concluidas;
create trigger avisar_localizacao_reaberta after delete on public.localizacoes_concluidas
  for each row execute function public.avisar_localizacao_reaberta();

-- a função "avisos" (servidor) usa estas tabelas
grant all on public.push_config, public.push_inscricoes, public.avisos, public.avisos_lidos, public.avisos_pref to service_role;

-- ---------- agendador: de hora em hora (prazo de teste e pendentes) ----------
-- Usa as extensões pg_cron e pg_net do Supabase (disponíveis no plano gratuito).
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;
select cron.schedule('avisos-rotina', '7 * * * *', $cron$
  select net.http_post(
    url     := 'https://wrhtisnejlpjsliplloz.supabase.co/functions/v1/avisos',
    headers := jsonb_build_object('Content-Type', 'application/json',
                                  'x-rotina', (select segredo_rotina from public.push_config where id = 1)),
    body    := '{"acao":"rotina"}'::jsonb,
    timeout_milliseconds := 20000)
$cron$);

-- conferência
select (select count(*) from public.avisos) as avisos,
       (select count(*) from public.push_inscricoes) as aparelhos,
       (select count(*) from cron.job where jobname = 'avisos-rotina') as agendador;
